// 10 语言翻译表（由 i18n.rs include）。
//
// 宏 `i18n_table!` 生成穷尽 match：任何 Key 遗漏都会编译失败，
// 保证每种语言都覆盖全部条目。

macro_rules! i18n_table {
    ($name:ident, $($key:ident => $str:literal),* $(,)?) => {
        fn $name(key: Key) -> &'static str {
            match key {
                $(Key::$key => $str,)*
            }
        }
    };
}

/// 按语言分发翻译
pub fn translate(lang: Lang, key: Key) -> &'static str {
    match lang {
        Lang::Zh => t_zh(key),
        Lang::En => t_en(key),
        Lang::De => t_de(key),
        Lang::Ja => t_ja(key),
        Lang::Ko => t_ko(key),
        Lang::Es => t_es(key),
        Lang::Pt => t_pt(key),
        Lang::Ar => t_ar(key),
        Lang::Ru => t_ru(key),
        Lang::Fr => t_fr(key),
    }
}

